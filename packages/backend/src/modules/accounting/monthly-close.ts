import { randomUUID } from "node:crypto";

import { z } from "zod";

import type { FinanceOperationScope } from "../finance-operations/contracts.js";
import type { AccountingSubmission } from "./contracts.js";
import {
  accountingMonthlyCloseAuditEventSchema,
  accountingMonthlyCloseSchema,
  type AccountingEvidenceStore,
  type AccountingMonthlyClose,
  type AccountingMonthlyCloseAuditEvent,
} from "./intake-contracts.js";
import {
  canLockMonthlyClose,
  canOpenMonthlyClose,
  canReadMonthlyClose,
  canSignMonthlyClose,
} from "./permissions.js";
import {
  AccountingSubmissionError,
  type AccountingActor,
} from "./submissions.js";

/**
 * First calendar month the close covers. The value is a code constant and never
 * an environment variable, because a month decides which finance data a sign
 * locks.
 */
export const FIRST_LIVE_MONTH = "2026-11";

/** Calendar month in `YYYY-MM` form accepted by the close. */
const periodMonthSchema = z.string().regex(/^\d{4}-(?:0[1-9]|1[0-2])$/u);

/** Content type of the stored monthly close report. */
const REPORT_CONTENT_TYPE = "application/json";

/**
 * Persistence boundary for the company-scoped monthly close. The port holds
 * the close rows, the approved submissions of a period, and the append-only
 * close audit trail.
 */
export interface AccountingMonthlyCloseRepository {
  /**
   * Finds the close of one company and period month.
   * @param input Actor-derived scope and period month.
   * @returns The stored close, or undefined when the month has no close.
   */
  findByPeriodMonth(input: {
    readonly scope: Readonly<FinanceOperationScope>;
    readonly periodMonth: string;
  }): Promise<AccountingMonthlyClose | undefined>;

  /**
   * Lists the approved submissions of one company and period month.
   * @param input Actor-derived scope and period month.
   * @returns The approved submissions of the period.
   */
  listApprovedSubmissions(input: {
    readonly scope: Readonly<FinanceOperationScope>;
    readonly periodMonth: string;
  }): Promise<readonly AccountingSubmission[]>;

  /**
   * Inserts one close row.
   * @param close Close snapshot generated by the domain.
   * @returns The stored close.
   */
  insert(close: AccountingMonthlyClose): Promise<AccountingMonthlyClose>;

  /**
   * Finds one close by id inside one company scope.
   * @param input Actor-derived scope and close identifier.
   * @returns The stored close, or undefined when unknown.
   */
  findById(input: {
    readonly scope: Readonly<FinanceOperationScope>;
    readonly closeId: string;
  }): Promise<AccountingMonthlyClose | undefined>;

  /**
   * Stores the changed fields of one close row.
   * @param close Close snapshot generated by the domain.
   * @returns The stored close.
   */
  save(close: AccountingMonthlyClose): Promise<AccountingMonthlyClose>;

  /**
   * Lists every close inside one company scope.
   * @param scope Actor-derived company boundary for the listing.
   * @returns The closes stored under the scope.
   */
  listByScope(
    scope: Readonly<FinanceOperationScope>,
  ): Promise<readonly AccountingMonthlyClose[]>;

  /**
   * Appends one row to the close audit trail.
   * @param event Audit event generated by the domain.
   * @returns The stored audit event.
   */
  recordAuditEvent(
    event: AccountingMonthlyCloseAuditEvent,
  ): Promise<AccountingMonthlyCloseAuditEvent>;
}

/**
 * Returns the company scope of the actor. The domain never accepts a
 * caller-supplied company.
 * @param actor Caller derived from the session.
 * @returns The company boundary of the actor.
 */
function actorScope(actor: AccountingActor): Readonly<FinanceOperationScope> {
  return { companyId: actor.companyId };
}

/**
 * Validates the period month of a close request.
 * @param periodMonth Candidate period month.
 * @returns The validated period month.
 * @throws AccountingSubmissionError when the month holds no calendar shape.
 */
function parsePeriodMonth(periodMonth: string): string {
  const parsed = periodMonthSchema.safeParse(periodMonth);
  if (!parsed.success) {
    throw new AccountingSubmissionError("invalid-input", parsed.error.issues);
  }
  if (parsed.data < FIRST_LIVE_MONTH) {
    throw new AccountingSubmissionError("invalid-input");
  }
  return parsed.data;
}

/**
 * Builds one append-only close audit row.
 * @param action Audit action of the step.
 * @param closeId Close the row belongs to.
 * @param actor Caller derived from the session.
 * @returns The validated audit event.
 */
function buildAuditEvent(
  action: "monthly-close-open" | "monthly-close-sign" | "monthly-close-lock",
  closeId: string,
  actor: AccountingActor,
): AccountingMonthlyCloseAuditEvent {
  return accountingMonthlyCloseAuditEventSchema.parse({
    id: randomUUID(),
    closeId,
    action,
    actorAccountId: actor.accountId,
    actorRole: actor.role,
    reason: null,
    createdAt: new Date().toISOString(),
  });
}

/**
 * Builds the report of one period month. The report holds the period month,
 * the approved submissions of the period, and the close row.
 * @param close Close row the report describes.
 * @param approvedSubmissions Approved submissions of the period.
 * @returns The report bytes stored as private evidence.
 */
function buildReportBytes(
  close: AccountingMonthlyClose,
  approvedSubmissions: readonly AccountingSubmission[],
): Uint8Array {
  const report = {
    periodMonth: close.periodMonth,
    close,
    submissions: approvedSubmissions,
  };
  return new TextEncoder().encode(JSON.stringify(report));
}

/**
 * Opens the close of one period month. The open collects the approved
 * submissions of the period, stores the report as private evidence, and keeps
 * the close at status `open`.
 * @param request Repository port, evidence port, actor, and period month.
 * @returns The stored open close.
 * @throws AccountingSubmissionError when the actor may not open a close, the month is invalid, or the month has a close.
 */
export async function openMonthlyClose(request: {
  readonly repository: AccountingMonthlyCloseRepository;
  readonly evidenceStore: AccountingEvidenceStore;
  readonly actor: AccountingActor;
  readonly periodMonth: string;
}): Promise<AccountingMonthlyClose> {
  if (!canOpenMonthlyClose(request.actor)) {
    throw new AccountingSubmissionError("forbidden");
  }

  const periodMonth = parsePeriodMonth(request.periodMonth);
  const scope = actorScope(request.actor);

  const existing = await request.repository.findByPeriodMonth({
    scope,
    periodMonth,
  });
  if (existing !== undefined) {
    throw new AccountingSubmissionError("conflict");
  }

  const approvedSubmissions =
    await request.repository.listApprovedSubmissions({ scope, periodMonth });

  const close = accountingMonthlyCloseSchema.parse({
    id: randomUUID(),
    periodMonth,
    status: "open",
    reportEvidenceReference: null,
    openedByAccountId: request.actor.accountId,
    openedAt: new Date().toISOString(),
    signedByAccountId: null,
    signedByRole: null,
    signedAt: null,
    lockedAt: null,
    scopeCompanyId: request.actor.companyId,
  });

  const stored = await request.evidenceStore.put({
    companyId: request.actor.companyId,
    contentType: REPORT_CONTENT_TYPE,
    body: buildReportBytes(close, approvedSubmissions),
  });

  const inserted = await request.repository.insert(
    accountingMonthlyCloseSchema.parse({
      ...close,
      reportEvidenceReference: stored.evidenceReference,
    }),
  );
  await request.repository.recordAuditEvent(
    buildAuditEvent("monthly-close-open", inserted.id, request.actor),
  );
  return inserted;
}

/**
 * Signs the close and locks it in the same call. Only the CEO signs. The call
 * writes the sign audit row and the lock audit row, and the stored status ends
 * at `locked`.
 * @param request Repository port, actor, and close identifier.
 * @returns The locked close.
 * @throws AccountingSubmissionError when the actor may not sign or the close is unknown.
 */
export async function signMonthlyClose(request: {
  readonly repository: AccountingMonthlyCloseRepository;
  readonly actor: AccountingActor;
  readonly closeId: string;
}): Promise<AccountingMonthlyClose> {
  if (!canSignMonthlyClose(request.actor)) {
    throw new AccountingSubmissionError("forbidden");
  }

  const scope = actorScope(request.actor);
  const close = await request.repository.findById({
    scope,
    closeId: request.closeId,
  });
  if (close === undefined) {
    throw new AccountingSubmissionError("not-found");
  }
  if (close.status === "locked") {
    return close;
  }
  if (close.status !== "open") {
    throw new AccountingSubmissionError("conflict");
  }

  const signed = await request.repository.save(
    accountingMonthlyCloseSchema.parse({
      ...close,
      status: "signed",
      signedByAccountId: request.actor.accountId,
      signedByRole: request.actor.role,
      signedAt: new Date().toISOString(),
    }),
  );
  await request.repository.recordAuditEvent(
    buildAuditEvent("monthly-close-sign", signed.id, request.actor),
  );

  return lockMonthlyClose({
    repository: request.repository,
    actor: request.actor,
    closeId: signed.id,
  });
}

/**
 * Locks one signed close. Only the CEO locks. The call writes the lock audit
 * row and the lock instant.
 * @param request Repository port, actor, and close identifier.
 * @returns The locked close.
 * @throws AccountingSubmissionError when the actor may not lock or the close is unknown or unsigned.
 */
export async function lockMonthlyClose(request: {
  readonly repository: AccountingMonthlyCloseRepository;
  readonly actor: AccountingActor;
  readonly closeId: string;
}): Promise<AccountingMonthlyClose> {
  if (!canLockMonthlyClose(request.actor)) {
    throw new AccountingSubmissionError("forbidden");
  }

  const scope = actorScope(request.actor);
  const close = await request.repository.findById({
    scope,
    closeId: request.closeId,
  });
  if (close === undefined) {
    throw new AccountingSubmissionError("not-found");
  }
  if (close.status === "locked") {
    return close;
  }
  if (close.status !== "signed") {
    throw new AccountingSubmissionError("conflict");
  }

  const locked = await request.repository.save(
    accountingMonthlyCloseSchema.parse({
      ...close,
      status: "locked",
      lockedAt: new Date().toISOString(),
    }),
  );
  await request.repository.recordAuditEvent(
    buildAuditEvent("monthly-close-lock", locked.id, request.actor),
  );
  return locked;
}

/**
 * Lists the closes visible to the actor. An OWNER and an ACCOUNTANT read every
 * close of the company; the CEO reads the locked closes only.
 * @param request Repository port and actor.
 * @returns The closes visible to the actor.
 * @throws AccountingSubmissionError when the actor holds no close read permission.
 */
export async function listMonthlyCloses(request: {
  readonly repository: AccountingMonthlyCloseRepository;
  readonly actor: AccountingActor;
}): Promise<readonly AccountingMonthlyClose[]> {
  if (
    !canOpenMonthlyClose(request.actor) &&
    !canSignMonthlyClose(request.actor)
  ) {
    throw new AccountingSubmissionError("forbidden");
  }

  const closes = await request.repository.listByScope(
    actorScope(request.actor),
  );
  return closes.filter((close) => canReadMonthlyClose(request.actor, close));
}
