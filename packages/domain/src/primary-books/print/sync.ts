import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import ts from "typescript";
import { PRINT_FONT_FILE, PRINT_KIT_PATHS, PRINT_THEME_TOKENS, printKitSchema, type PrintKit } from "./contracts.js";
import { assertPrintKitSafe } from "./kit-guard.js";

/** Kit file and font folder, relative to the monorepo root. */
const KIT_FILE = "packages/domain/src/primary-books/print/kit.generated.ts";
const FONT_DIR = "apps/primary-advantage/public/print-fonts";
const FIXTURE_DIR = "packages/domain/src/primary-books/print/__fixtures__";

const git = (repo: string, args: string[]): string =>
  execFileSync("git", ["-C", repo, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 * 1024 * 1024 });
const gitBuffer = (repo: string, args: string[]): Buffer =>
  execFileSync("git", ["-C", repo, ...args], { maxBuffer: 64 * 1024 * 1024 });

const KIT_PATHSPEC = [
  PRINT_KIT_PATHS.template,
  PRINT_KIT_PATHS.icons,
  PRINT_KIT_PATHS.styles,
  PRINT_KIT_PATHS.utils,
  PRINT_KIT_PATHS.fontsDir,
];

/** Reads the origin URL of a repository; falls back to "Workbooks" with no remote. */
function originOf(repo: string): string {
  try {
    return git(repo, ["remote", "get-url", "origin"]).trim() || "Workbooks";
  } catch {
    return "Workbooks";
  }
}

/**
 * Finds the newest Workbooks commit that changed a kit path.
 * @param workbooks Path of the Workbooks repository.
 * @returns The full commit id.
 */
export function latestKitCommit(workbooks: string): string {
  return git(workbooks, ["log", "-1", "--format=%H", "HEAD", "--", ...KIT_PATHSPEC]).trim();
}

/**
 * Runs `getPrintStyles` of the Workbooks source for A4 with no cover.
 * @param stylesSource TypeScript source of `styles.ts`.
 * @returns The print CSS with theme placeholders.
 * @throws When the source has no `getPrintStyles` function.
 */
export function renderKitCss(stylesSource: string): string {
  const js = ts.transpileModule(stylesSource, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const exports: Record<string, unknown> = {};
  new Function("exports", "require", js)(exports, () => ({}));
  const fn = exports.getPrintStyles as ((theme: object, opts: object) => string) | undefined;
  if (!fn) throw new Error("styles.ts has no getPrintStyles");
  const theme = { primary: PRINT_THEME_TOKENS.primary, secondary: PRINT_THEME_TOKENS.secondary, gradient: PRINT_THEME_TOKENS.gradient };
  return fn(theme, { pageSize: "210mm 297mm", cover: false });
}

/**
 * Reads the kit files at one Workbooks commit.
 * @param workbooks Path of the Workbooks repository (read only).
 * @param commit Commit id to read.
 * @returns The kit and the font file bytes.
 * @throws When a kit file is missing or the guard refuses the kit.
 */
export function buildKit(workbooks: string, commit: string): { kit: PrintKit; fonts: Map<string, Buffer> } {
  const full = git(workbooks, ["rev-parse", commit]).trim();
  const show = (path: string) => git(workbooks, ["show", `${full}:${path}`]);
  const names = git(workbooks, ["ls-tree", "--name-only", full, PRINT_KIT_PATHS.fontsDir])
    .split("\n")
    .map((n) => n.trim().split("/").pop() ?? "")
    .filter((n) => PRINT_FONT_FILE.test(n));
  const fonts = new Map(names.map((n) => [n, gitBuffer(workbooks, ["show", `${full}:${PRINT_KIT_PATHS.fontsDir}${n}`])]));
  const kit = printKitSchema.parse({
    template: show(PRINT_KIT_PATHS.template),
    iconsSource: show(PRINT_KIT_PATHS.icons),
    utilsSource: show(PRINT_KIT_PATHS.utils),
    css: renderKitCss(show(PRINT_KIT_PATHS.styles)),
    fonts: names.sort(),
    sourceRepo: originOf(workbooks),
    commit: full,
    commitDate: git(workbooks, ["show", "-s", "--format=%cI", full]).trim(),
  });
  assertPrintKitSafe(kit);
  return { kit, fonts };
}

/**
 * Writes the generated kit module and the font folder.
 * @param repoRoot Monorepo root.
 * @param built Result of `buildKit`.
 */
export function writeKit(repoRoot: string, built: { kit: PrintKit; fonts: Map<string, Buffer> }): void {
  const file = join(repoRoot, KIT_FILE);
  mkdirSync(join(file, ".."), { recursive: true });
  const header = `// GENERATED by packages/domain/scripts/sync-print-kit.ts. Do not edit.\n// Source: ${built.kit.sourceRepo} at ${built.kit.commit} (${built.kit.commitDate}).\n`;
  writeFileSync(file, `${header}import type { PrintKit } from "./contracts.js";\n\n/** The Workbooks primary print kit. */\nexport const PRINT_KIT: PrintKit = ${JSON.stringify(built.kit, null, 2)};\n`);
  const dir = join(repoRoot, FONT_DIR);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const [name, bytes] of built.fonts) writeFileSync(join(dir, name), bytes);
}

/**
 * Compares the kit commit with the newest Workbooks commit of the kit paths.
 * @param workbooks Path of the Workbooks repository.
 * @param repoRoot Monorepo root.
 * @returns The kit commit, the newest commit, and whether they match.
 */
export function checkKit(workbooks: string, repoRoot: string): { kit: string; latest: string; ok: boolean } {
  const text = existsSync(join(repoRoot, KIT_FILE)) ? readFileSync(join(repoRoot, KIT_FILE), "utf8") : "";
  const kit = /"commit": "([0-9a-f]{40})"/.exec(text)?.[1] ?? "";
  const latest = latestKitCommit(workbooks);
  return { kit, latest, ok: kit === latest };
}

/**
 * Copies the golden fixture of one lesson from a Workbooks commit: the print data and the HTML body that
 * Workbooks' own `renderMultipleLessons` made without the answer key page. Workbooks made the HTML
 * at the export commit, so this copy needs no Workbooks render at the kit commit.
 * @param workbooks Path of the Workbooks repository.
 * @param repoRoot Monorepo root.
 * @param spec Book and lesson number, for example `origins-3.2/5`.
 * @param commit Workbooks commit that holds the export and the golden file.
 * @returns The two written file paths.
 * @throws When the commit has no print data or no golden file for the lesson.
 */
export function copyFixture(workbooks: string, repoRoot: string, spec: string, commit: string): string[] {
  const [book, n] = spec.split("/");
  const number = Number(n);
  if (!/^[a-z0-9.-]+$/.test(book ?? "") || !Number.isInteger(number) || number < 1) throw new Error(`--fixture needs <book>/<n>, got "${spec}"`);
  const dir = `content/primary/${book}/print`;
  const files = git(workbooks, ["ls-tree", "--name-only", commit, `${dir}/`]).split("\n").filter((f) => f.endsWith(".json"));
  const json = files.find((f) => (JSON.parse(git(workbooks, ["show", `${commit}:${f}`])) as { lessonNumber?: number }).lessonNumber === number);
  if (!json) throw new Error(`no print data for ${spec} at ${commit}`);
  const golden = `${dir}/golden/lesson-${String(number).padStart(2, "0")}-no-key.html`;
  const out = join(repoRoot, FIXTURE_DIR);
  mkdirSync(out, { recursive: true });
  const short = commit.slice(0, 7);
  const written = [`${book}-${number}@${short}.json`, `${book}-${number}-no-key-body@${short}.html`].map((name) => join(out, name));
  writeFileSync(written[0], git(workbooks, ["show", `${commit}:${json}`]));
  const html = git(workbooks, ["show", `${commit}:${golden}`]);
  const start = html.indexOf("<body>");
  const end = html.lastIndexOf("</body>");
  if (start < 0 || end < start) throw new Error(`golden file ${golden} has no body`);
  writeFileSync(written[1], html.slice(start + "<body>".length, end));
  return written;
}

/**
 * Runs the sync script.
 * Usage: `tsx scripts/sync-print-kit.ts [--workbooks <dir>] [--repo-root <dir>] [--commit <id>] [--check]`
 * Fixture: `tsx scripts/sync-print-kit.ts --fixture <book>/<n> --commit <export commit>`
 * @param argv Command line arguments without the node and script names.
 * @returns Exit code: 0 done, 1 the check found a newer kit commit, 2 config error or a dirty kit path.
 */
export async function runSyncPrintKit(argv: string[]): Promise<number> {
  const flag = (name: string) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : undefined);
  const workbooks = resolve(flag("--workbooks") ?? join(homedir(), "Desktop", "Workbooks"));
  const repoRoot = resolve(flag("--repo-root") ?? git(process.cwd(), ["rev-parse", "--show-toplevel"]).trim());
  try {
    if (argv.includes("--check")) {
      const r = checkKit(workbooks, repoRoot);
      console.log(r.ok ? `print kit is current (${r.kit})` : `print kit is stale: kit ${r.kit || "none"}, newest ${r.latest}`);
      return r.ok ? 0 : 1;
    }
    if (argv.includes("--fixture")) {
      const commit = flag("--commit");
      if (!commit) throw new Error("--fixture needs --commit <Workbooks export commit>");
      for (const file of copyFixture(workbooks, repoRoot, flag("--fixture") ?? "", commit)) console.log(`fixture written: ${file}`);
      return 0;
    }
    const dirty = git(repoRoot, ["status", "--porcelain", "--", KIT_FILE, FONT_DIR]).trim();
    if (dirty) {
      console.error(`kit path has local changes; commit or restore it first:\n${dirty}`);
      return 2;
    }
    const wbDirty = git(workbooks, ["status", "--porcelain", "--", ...KIT_PATHSPEC]).trim();
    if (wbDirty) {
      console.error(`Workbooks kit path has local changes; commit or restore it first:\n${wbDirty}`);
      return 2;
    }
    const built = buildKit(workbooks, flag("--commit") ?? latestKitCommit(workbooks));
    writeKit(repoRoot, built);
    console.log(`print kit written at ${built.kit.commit} (${built.kit.commitDate}); ${built.fonts.size} font files`);
    return 0;
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    return 2;
  }
}
